require 'digest'
require 'tmpdir'

# Extract only selection methods. No SwiftUI, scanner, executor or package manager
# is linked by the resulting executable; the surrounding state lives in memory.
root = File.expand_path('../..', __dir__)
out = ARGV.fetch(0) { abort 'usage: ruby bulk-generate.rb EXISTING_TEMP_DIRECTORY' }
abort 'output directory must exist' unless File.directory?(out)
out = File.realpath(out)
temp_roots = [Dir.tmpdir, '/tmp', '/private/tmp'].map do |path|
  File.realpath(path) if File.directory?(path)
end.compact.uniq
abort 'output directory must be inside a temporary directory' unless temp_roots.any? { |path| out.start_with?(path + '/') }

def extract(source, path, first, following)
  abort "missing or duplicated source marker: #{path}: #{first}" unless source.scan(first).length == 1
  abort "missing or duplicated boundary marker: #{path}: #{following}" unless source.scan(following).length == 1
  start = source.index(first)
  finish = source.index(following, start + first.length)
  abort "source boundary precedes method: #{path}: #{first}" unless finish
  original = source[start...finish].rstrip
  abort "incomplete method boundary: #{path}: #{first}" unless original.end_with?('}')
  # Fail closed if a later implementation adds external work to a selection method.
  forbidden = /\b(?:FileManager|NSWorkspace|Process|ProcessRunner|Task|URLSession|PackageManager|SoftwareService|CleanupScanStore|[A-Za-z]*Executor)\b/
  abort "selection extraction contains external-work dependency: #{path}: #{first}" if original.match?(forbidden)
  line = source[0...start].count("\n") + 1
  puts "EXTRACT #{path}:#{line} #{first.strip} SHA256=#{Digest::SHA256.hexdigest(original)}"
  # Only access control changes; method bodies are copied verbatim.
  original.sub(/\A    private /, '    ') + "\n"
end

app_path = 'MacDefier/Views/Software/UninstallSheet.swift'
cli_path = 'MacDefier/Views/Software/CliUninstallSheet.swift'
ai_path = 'MacDefier/AI/AIToolCleanupService.swift'
sources = [app_path, cli_path, ai_path].to_h { |path| [path, File.read(File.join(root, path))] }
sources.each { |path, source| puts "SOURCE #{path} SHA256=#{Digest::SHA256.hexdigest(source)}" }

app_markers = [
  '    private func canBulkSelect(_ item: ResidualItem) -> Bool {',
  '    private func selectAllItems() {',
  '    private func clearItemSelection() {',
  '    private func applyKeepUserData() {',
  '    private func runUninstall(forceQuitIfNeeded: Bool = false) async {'
]
app_methods = app_markers.each_cons(2).map { |first, following| extract(sources.fetch(app_path), app_path, first, following) }.join("\n")

cli_markers = [
  '    private var hasOptions: Bool {',
  '    private var allOptionsSelected: Bool {',
  '    private func selectAllOptions() {',
  '    private func clearAllOptions() {',
  '    private var commandPreview: String {'
]
cli_methods = cli_markers.each_cons(2).map { |first, following| extract(sources.fetch(cli_path), cli_path, first, following) }.join("\n")
cli_permission = extract(sources.fetch(cli_path), cli_path,
                         '    private var canUninstall: Bool { !tool.protected }',
                         '    /// Hermes is uninstallable')
ai_method = extract(sources.fetch(ai_path), ai_path, '    func selectAllEligible() {',
                    '    var selectedCandidates: [AICleanupCandidate]')

generated = <<~SWIFT
  // Generated by bulk-generate.rb from current product method bodies.
  // Stub data and assertions are in BulkMain.swift; no filesystem or executor is linked.
  import Foundation

  final class AppBulkProbe {
      let app: AppStub
      var items: [ResidualItem]
      var keepUserData: Bool
      init(app: AppStub, items: [ResidualItem], keepUserData: Bool = true) {
          self.app = app; self.items = items; self.keepUserData = keepUserData
      }
  #{app_methods}
  }

  final class CLIBulkProbe {
      let tool: CliToolStub
      let hasProgram: Bool // Preset input, not the live filesystem-backed inventory probe.
      var stopAgents = false
      var uninstallProgram = false
      var selectedData = Set<String>()
      init(tool: CliToolStub, hasProgram: Bool) { self.tool = tool; self.hasProgram = hasProgram }
  #{cli_permission}
  #{cli_methods}
  }

  final class AIBulkProbe {
      var phase = AIPhaseStub.preview
      var requiresRescan = false
      var visibleCandidates: [AICandidateStub]
      var selectedIDs = Set<String>()
      var refreshCalls = 0
      init(visibleCandidates: [AICandidateStub]) { self.visibleCandidates = visibleCandidates }
      func refreshSelection() { refreshCalls += 1 }
  #{ai_method}
  }
SWIFT

destination = File.join(out, 'BulkExtracted.swift')
File.write(destination, generated)
puts "GENERATED #{destination} SHA256=#{Digest::SHA256.hexdigest(generated)}"
